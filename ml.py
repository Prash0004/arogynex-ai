"""GramHealth AI - synthetic data + ML training pipeline.

ALL DATA HERE IS SYNTHETIC. The label is generated from a made-up function, so
metrics only show the pipeline works. They say nothing about real clinical accuracy.
Target (synthetic): 'elevated_bp_flag' - screening flag for further human review.
"""
import json, time, os
import numpy as np, pandas as pd, joblib
from sklearn.model_selection import train_test_split, GroupShuffleSplit
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.inspection import permutation_importance
from sklearn.metrics import (confusion_matrix, precision_score, recall_score, f1_score,
                             roc_auc_score, average_precision_score)

HERE = os.path.dirname(__file__)
ART = os.path.join(HERE, "artifacts")
FEATURES = ["age", "bmi", "waist_cm", "glucose_mgdl", "activity_level", "fruit_veg_per_day", "salt_score"]
SEED = 42


def generate_synthetic(n=1500, seed=SEED):
    rng = np.random.default_rng(seed)
    age = rng.integers(18, 80, n)
    bmi = np.clip(rng.normal(23.5, 4, n), 14, 45)
    waist = np.clip(bmi * 3.6 + rng.normal(0, 6, n), 50, 140)
    glucose = np.clip(rng.normal(98, 20, n) + (age - 40) * 0.2, 60, 300)
    activity = rng.integers(0, 4, n)          # 0 sedentary .. 3 very active
    fv = np.clip(rng.normal(2.5, 1.2, n), 0, 8)
    salt = rng.integers(0, 4, n)
    z = (-6.2 + 0.045 * age + 0.11 * bmi + 0.012 * (glucose - 100)
         - 0.25 * activity - 0.08 * fv + 0.3 * salt)
    p = 1 / (1 + np.exp(-z))
    y = (rng.random(n) < p).astype(int)
    df = pd.DataFrame(dict(age=age, bmi=bmi.round(1), waist_cm=waist.round(0),
                           glucose_mgdl=glucose.round(0), activity_level=activity,
                           fruit_veg_per_day=fv.round(1), salt_score=salt))
    # inject realistic missingness (never filled with zero)
    for c, f in [("waist_cm", .15), ("glucose_mgdl", .25)]:
        df.loc[rng.random(n) < f, c] = np.nan
    df["participant_group"] = np.arange(n) // 1   # one row per synthetic participant
    df["elevated_bp_flag"] = y
    return df


def data_quality(df):
    return {
        "rows": int(len(df)),
        "missing_pct": {c: round(float(df[c].isna().mean() * 100), 1) for c in FEATURES},
        "duplicates": int(df.duplicated().sum()),
        "class_balance": {str(k): int(v) for k, v in df["elevated_bp_flag"].value_counts().items()},
        "source": "Synthetic - generated by ml.generate_synthetic (seed 42)",
        "license": "N/A (generated). Not real-world data.",
    }


def _models():
    return {
        "Logistic Regression": LogisticRegression(max_iter=1000),
        "Decision Tree": DecisionTreeClassifier(max_depth=5, random_state=SEED),
        "Random Forest": RandomForestClassifier(n_estimators=200, max_depth=8, random_state=SEED),
    }


def _metrics(y, pred, proba):
    tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()
    m = dict(tn=int(tn), fp=int(fp), fn=int(fn), tp=int(tp), n_test=int(len(y)),
             positives=int(y.sum()),
             precision=float(precision_score(y, pred, zero_division=0)),
             recall=float(recall_score(y, pred, zero_division=0)),
             specificity=float(tn / (tn + fp)) if (tn + fp) else None,
             f1=float(f1_score(y, pred, zero_division=0)))
    if len(set(y)) == 2:
        m["roc_auc"] = float(roc_auc_score(y, proba))
        m["pr_auc"] = float(average_precision_score(y, proba))
    return m


def train_all():
    os.makedirs(ART, exist_ok=True)
    df = generate_synthetic()
    X, y, g = df[FEATURES], df["elevated_bp_flag"], df["participant_group"]
    # split by participant (group) to prevent leakage
    gss = GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=SEED)
    tr, te = next(gss.split(X, y, g))
    assert set(g.iloc[tr]).isdisjoint(set(g.iloc[te])), "leakage between train and test"
    Xtr, Xte, ytr, yte = X.iloc[tr], X.iloc[te], y.iloc[tr], y.iloc[te]
    results, best, best_auc = {}, None, -1
    for name, clf in _models().items():
        pipe = Pipeline([("impute", SimpleImputer(strategy="median")),
                         ("scale", StandardScaler()), ("clf", clf)])
        t0 = time.time(); pipe.fit(Xtr, ytr); dt = time.time() - t0
        proba = pipe.predict_proba(Xte)[:, 1]
        res = _metrics(yte, (proba >= 0.5).astype(int), proba)
        res["train_seconds"] = round(dt, 3)
        pi = permutation_importance(pipe, Xte, yte, n_repeats=10, random_state=SEED, scoring="roc_auc")
        res["feature_importance"] = {f: float(v) for f, v in zip(FEATURES, pi.importances_mean)}
        results[name] = res
        if res["roc_auc"] > best_auc:
            best, best_auc = (name, pipe), res["roc_auc"]
    version = time.strftime("v%Y%m%d-%H%M%S")
    joblib.dump(best[1], os.path.join(ART, "model.joblib"))
    report = dict(version=version, best_model=best[0], dataset="synthetic (seed 42)",
                  split="80/20 group split by participant", features=FEATURES, target="elevated_bp_flag (synthetic)",
                  quality=data_quality(df), results=results,
                  warning="Synthetic data: metrics demonstrate the pipeline only, not clinical validity.")
    json.dump(report, open(os.path.join(ART, "report.json"), "w"), indent=2)
    return report


def load_report():
    p = os.path.join(ART, "report.json")
    return json.load(open(p)) if os.path.exists(p) else None


def predict(values: dict):
    """values: feature->number or None. Returns probability from the persisted pipeline."""
    path = os.path.join(ART, "model.joblib")
    if not os.path.exists(path):
        return None
    pipe = joblib.load(path)
    row = pd.DataFrame([{f: (np.nan if values.get(f) is None else values[f]) for f in FEATURES}])
    return float(pipe.predict_proba(row)[0, 1])


if __name__ == "__main__":
    r = train_all()
    print(r["best_model"], {k: round(v["roc_auc"], 3) for k, v in r["results"].items()})
